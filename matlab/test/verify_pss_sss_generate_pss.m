    im_abs = abs(imag(lte_toolbox_pss_element) - imag(my_pss_generation_element));
    
    if re_abs > 1e-10 || im_abs > 1e-10
        fprintf('NOK re_abs=%.20e, im_abs=%.20e \n', re_abs, im_abs);
